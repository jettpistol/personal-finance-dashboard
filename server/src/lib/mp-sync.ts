/** CSV with quoted fields; the separator is whichever of ; , or tab the header uses most. */
export function parseCsv(text: string): string[][] {
  const src = text.replace(/^﻿/, '');
  const nl = src.search(/\r?\n/);
  const head = nl < 0 ? src : src.slice(0, nl);
  const sep = [';', ',', '\t'].map((c) => [c, head.split(c).length] as const).sort((a, b) => b[1] - a[1])[0][0];
  const rows: string[][] = [];
  let row: string[] = [];
  let cell = '';
  let quoted = false;
  for (let i = 0; i < src.length; i++) {
    const ch = src[i];
    if (quoted) {
      if (ch === '"' && src[i + 1] === '"') {
        cell += '"';
        i++;
      } else if (ch === '"') quoted = false;
      else cell += ch;
    } else if (ch === '"' && cell === '') quoted = true;
    else if (ch === sep) {
      row.push(cell);
      cell = '';
    } else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && src[i + 1] === '\n') i++;
      row.push(cell);
      if (row.some((c) => c !== '')) rows.push(row);
      row = [];
      cell = '';
    } else cell += ch;
  }
  row.push(cell);
  if (row.some((c) => c !== '')) rows.push(row);
  return rows;
}

/** "225.96", "-43.04", "1,234.56" or "1.234,56" → cents. Empty → 0. */
export function mpAmount(raw: string | undefined): number {
  const s = (raw ?? '').trim().replace(/\s/g, '');
  if (!s) return 0;
  let m = /^(-)?(\d+)(?:\.(\d{1,2}))?$/.exec(s) ?? /^(-)?(\d{1,3}(?:,\d{3})+)(?:\.(\d{1,2}))?$/.exec(s);
  if (m) return (m[1] ? -1 : 1) * (Number(m[2].replace(/,/g, '')) * 100 + Number((m[3] ?? '').padEnd(2, '0')));
  m = /^(-)?(\d{1,3}(?:\.\d{3})*|\d+),(\d{1,2})$/.exec(s);
  if (m) return (m[1] ? -1 : 1) * (Number(m[2].replace(/\./g, '')) * 100 + Number(m[3].padEnd(2, '0')));
  throw new SyncError(`Mercado Pago mandó un monto que no se pudo leer: «${s.slice(0, 20)}».`);
}

/** The household's date of a report timestamp ("2026-10-12T15:07:53.000-03:00"). */
function localDate(iso: string): string {
  const t = Date.parse(iso);
  if (Number.isNaN(t)) throw new SyncError(`Mercado Pago mandó una fecha que no se pudo leer: «${iso.slice(0, 30)}».`);
  return today(new Date(t));
}

const table = (text: string) => {
  const [header, ...rows] = parseCsv(text);
  const cols = (header ?? []).map((h) => h.trim().toUpperCase());
  return rows.map((r) => Object.fromEntries(cols.map((c, i) => [c, (r[i] ?? '').trim()])) as Record<string, string>);
};

