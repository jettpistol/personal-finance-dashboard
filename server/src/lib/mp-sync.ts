function afterImport(created: number[]) {
  for (const id of created) {
    autoLink(id);
    const tx = getTx(id);
    if (tx) checkBudgetAlerts(tx).catch((e) => console.error('budget alert failed', e));
  }
}

const running = new Set<number>();
// When each person's sync last asked Mercado Pago for a report, so a failing one waits an hour too.
const lastAsked = new Map<number, number>();

/**
 * One step of the sync: asks for the next report, or collects the one asked for. `start` asks even
 * when nothing is due (the person clicked). `wrap` lets a request journal the writes for Deshacer.
 */
export async function advanceSync(userId: number, opts: { start?: boolean; wrap?: <T>(fn: () => T) => T } = {}) {
  const wrap = opts.wrap ?? (<T>(fn: () => T) => fn());
  const stored = storedToken(userId);
  if (!stored) throw new HttpError(400, 'Conectá tu cuenta de Mercado Pago de nuevo.');
  const account = linkedAccount(userId);
  if (running.has(userId)) return syncView(userId);
  running.add(userId);
  try {
    const r = getRow(userId);
    const pending = r?.pending ? (JSON.parse(r.pending) as Pending) : null;
    if (!pending) {
      const last = Math.max(Date.parse(r?.last_sync_at ?? '1970-01-01'), lastAsked.get(userId) ?? 0);
      // The first import goes on month by month until today; after that, once an hour.
      const due = opts.start || (r?.status === 'fetching' && !r.live) || (r?.live && Date.now() - last >= SYNC_EVERY_MS);
      if (!due || (r?.status === 'review' && !r.live)) return syncView(userId);
      const from = r?.synced_until ? Date.parse(r.synced_until) - OVERLAP_MS : localMidnight(historyStartOf(userId));
      const end = Math.min(from + CHUNK_DAYS * 86_400_000, Date.now() - 60_000);
      lastAsked.set(userId, Date.now());
      const next = await requestRange(stored.token, iso(from), iso(end));
      log(`pedido ${next.begin}→${next.end}: ${next.kinds.join(' y ')}`);
      save(userId, { status: r?.live ? 'live' : 'fetching', pending: JSON.stringify(next), last_error: null });
      return syncView(userId);
    }

    if (Date.now() - pending.requested_at > GIVE_UP_MS)
      throw new SyncError(`Mercado Pago no entregó el reporte en 30 minutos${pending.note ? ` (${pending.note.replace(/\.$/, '')})` : ''}. Probá de nuevo más tarde.`);
    // Waiting or unreachable: keep what it said, so the screen shows it, and try again next time.
    const hold = (note: string, failed = false) => {
      const fails = failed ? (pending.fails ?? 0) + 1 : 0;
      if (fails >= 6) throw new SyncError(`${note} Probá de nuevo más tarde.`);
      save(userId, { pending: JSON.stringify({ ...pending, note, fails }) });
      return syncView(userId);
    };
    let release: Awaited<ReturnType<typeof fetchReport>>;
    try {
      release = await fetchReport(stored.token, 'release_report', pending);
    } catch (e) {
      if (e instanceof HttpError) return hold(e.message, true);
      throw e;
    }
    if ('wait' in release) return hold(release.wait);
    const text = release.text;
    let detail: string | null = null;
    if (pending.kinds.includes('settlement_report')) {
      const d = await fetchReport(stored.token, 'settlement_report', pending).catch(() => null);
      detail = d && 'text' in d ? d.text : null;
      // The transactions report only adds store names: give it a few minutes, then go without it.
      if (detail === null && Date.now() - pending.requested_at < 5 * 60_000) return hold(d && 'wait' in d ? d.wait : 'Esperando el reporte de todas las transacciones.');
    }

    const parsed = parseReleaseReport(text, detail);
    markReportsReady(userId, detail === null ? ['release_report'] : ['release_report', 'settlement_report']);
    return wrap(() => {
      const created = db().transaction((): number[] => {
        const cur = getRow(userId);
        const review = reviewOf(cur);
        const known = new Set([...review.dismissed, ...review.items.map((i) => i.external_id)]);
        const items = toItems(parsed, account, known);
        const base = { pending: null, synced_until: pending.end, last_sync_at: new Date().toISOString(), last_error: null, balance: parsed.closing ?? cur?.balance ?? null, balance_at: parsed.closing === null ? (cur?.balance_at ?? null) : pending.end };
        if (!cur?.live) {
          // First import: everything waits for the review, chunk after chunk until today.
          const opening = cur?.opening ?? (parsed.initial === null ? null : JSON.stringify({ date: historyStartOf(userId), amount: parsed.initial }));
          // More to fetch only if the range stopped short of when it was asked for (a month's cap).
          const more = Date.parse(pending.end) < pending.requested_at - 10 * 60_000;
          save(userId, { ...base, status: more ? 'fetching' : 'review', opening, review: JSON.stringify({ ...review, items: [...review.items, ...items], skipped: review.skipped + parsed.skipped }) });
          return [];
        }
        // Live: what's complete goes in; what needs a choice waits.
        const now = items.filter(ready);
        const later = items.filter((i) => !ready(i));
        let done: number[] = [];
        if (now.length) {
          const res = commitImportRows(account, now.map(toCommit), userId, { file_name: `Mercado Pago · ${pending.end.slice(0, 10)}` });
          done = res.created;
          if (res.imported + res.merged)
            logAction({
              userId,
              section: 'Mercado Pago',
              action: 'importar',
              summary: `Mercado Pago trajo ${res.imported} movimiento${res.imported === 1 ? '' : 's'}${res.merged ? ` y completó ${res.merged} cargado${res.merged === 1 ? '' : 's'} a mano` : ''}`,
              entity: 'import_batch',
              entityId: res.batch_id,
              privateTo: userId,
            });
        }
        save(userId, { ...base, status: 'live', review: JSON.stringify({ ...review, items: [...review.items, ...later], skipped: review.skipped + parsed.skipped }) });
        return done;
      })();
      afterImport(created);
      return syncView(userId);
    });
  } catch (e) {
    if (!(e instanceof SyncError)) throw e;
    save(userId, { status: 'error', pending: null, last_error: e.message });
    return syncView(userId);
  } finally {
    running.delete(userId);
  }
}

/** Stops waiting for a report asked for; a first import can then be started again from scratch. */
export function cancelSync(userId: number) {
  const r = getRow(userId);
  if (!r?.pending) return syncView(userId);
  log('búsqueda cancelada');
  save(userId, r.live ? { pending: null, status: 'live' } : { pending: null, status: 'error', last_error: 'Búsqueda cancelada.' });
  return syncView(userId);
}

// ---- The review ----

export function reviewItems(userId: number) {
  const r = getRow(userId);
  const review = reviewOf(r);
  const opening = !r?.live && r?.opening ? (JSON.parse(r.opening) as { date: string; amount: number }) : null;
  return { items: review.items, skipped: review.skipped, opening, first: !r?.live, account: mpAccountState(userId).account };
}

/**
 * Saves the reviewed rows (the person's edits travel in `rows`, matched by external_id), drops the
 * unticked ones for good, and on the first review sets the account's starting balance from
 * Mercado Pago's own figure. After this the account is live.
 */
export function commitReview(userId: number, rows: (CommitRow & { include: boolean })[], useOpening: boolean) {
  const r = getRow(userId);
  if (!r) throw new HttpError(400, 'No hay movimientos de Mercado Pago para revisar.');
  const account = linkedAccount(userId);
  const review = reviewOf(r);
  const byId = new Map(rows.filter((x) => x.external_id).map((x) => [x.external_id!, x]));
  // Amounts, dates and ids are Mercado Pago's; the review only changes how a movement is filed.
  const chosen = review.items
    .filter((it) => byId.get(it.external_id)?.include)
    .map((it) => {
      const e = byId.get(it.external_id)!;
      return { ...toCommit(it), type: e.type, category_id: e.category_id, description: e.description, merchant: e.merchant, notes: e.notes, tags: e.tags, to_account_id: e.to_account_id, is_shared: e.is_shared };
    });
  const dropped = review.items.filter((it) => !byId.get(it.external_id)?.include).map((it) => it.external_id);
  const result = chosen.length ? commitImportRows(account, chosen, userId, { file_name: 'Mercado Pago · revisión' }) : null;
  let openingSet: number | null = null;
  if (!r.live && useOpening && r.opening) {
    const o = JSON.parse(r.opening) as { date: string; amount: number };
    const before = accountBalances(loadAccounts(), addDays(o.date, -1)).get(account.id) ?? 0;
    const current = (db().prepare('SELECT opening_balance FROM accounts WHERE id = ?').get(account.id) as { opening_balance: number }).opening_balance;
    openingSet = current + (o.amount - before);
    db().prepare('UPDATE accounts SET opening_balance = ? WHERE id = ?').run(openingSet, account.id);
  }
  // Rows that couldn't be saved (a transfer without its account) stay for the next review.
  const failed = new Set(result?.failures.map((f) => f.external_id) ?? []);
  const keep = review.items.filter((it) => failed.has(it.external_id));
  save(userId, {
    status: 'live',
    live: 1,
    opening: null,
    review: JSON.stringify({ items: keep, dismissed: [...review.dismissed, ...dropped].slice(-MAX_DISMISSED), skipped: 0 }),
  });
  return { imported: result?.imported ?? 0, merged: result?.merged ?? 0, failures: result?.failures ?? [], created: result?.created ?? [], opening: openingSet, account: account.name, batch_id: result?.batch_id ?? null };
}

export function afterReview(created: number[]) {
  afterImport(created);
}

/** Sync state of people who have it running in the current profile, for the scheduler. */
export async function syncDue() {
  const rows = db().prepare(`SELECT user_id FROM mp_sync WHERE live = 1 OR pending IS NOT NULL OR status = 'fetching'`).all() as { user_id: number }[];
  for (const { user_id } of rows) {
    if (!storedToken(user_id) || !mpAccountState(user_id).account) continue;
    try {
      await advanceSync(user_id);
    } catch (e) {
      console.error(`[mercadopago] sync for user ${user_id} failed:`, (e as Error).message);
    }
  }
}
