// Bringing each person's Mercado Pago movements into their Mercado Pago account in Cuentas.
//
// Source: the released-money report (every movement of the available balance, with the balance at
// the start), detailed with the transactions report (store, description) when that one is there.
// Both are asked for a date range, generated by Mercado Pago in a few minutes, then downloaded.
//
// The first time, everything from the history start waits in a review (like Importar); once that
// review is saved the account is live: new movements go in by themselves every hour, and only the
// ones missing something (where a withdrawal went) wait for review. A movement typed by hand with
// the same amount, a day apart at most, is completed instead of doubled.
//
// State lives per person in each data profile (mp_sync), so a profile only fills if its owner
// starts it there.

export const MP_PLATFORM = 'Mercado Pago';
// What the sync did, in the server's terminal (never the token or the report's contents), for diagnosis.
const log = (msg: string) => console.log(`[mercadopago] ${msg}`);
// Report statuses that mean "not yet" and "won't be". Anything else with a file is tried.
const IN_PROGRESS = /^(pending|processing|in_progress|in-progress|queued|waiting|generating|created|scheduled)$/;
const FAILED = /^(error|failed|failure|rejected|cancell?ed|expired|deleted)$/;
const SYNC_EVERY_MS = 60 * 60_000;
const GIVE_UP_MS = 30 * 60_000;
const CHUNK_DAYS = 31;
const OVERLAP_MS = 2 * 86_400_000;
const MAX_DISMISSED = 2000;

export type MpItem = ReturnType<typeof buildPreviewItems>[number] & { external_id: string; fees: Fee[]; merge_with: number | null };

// note: what Mercado Pago said on the last check (shown under «Buscando…»); fails: checks in a row
