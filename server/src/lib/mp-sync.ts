/** Report rows as review items: rules and categories applied, known ones dropped, hand-typed twins found. */
function toItems(parsed: ParsedReport, account: Account, known: Set<string>): MpItem[] {
  const exists = db().prepare('SELECT 1 FROM transactions WHERE external_id = ? LIMIT 1');
  const fresh = parsed.rows.filter((r) => !known.has(r.external_id) && !exists.get(r.external_id));
  const items = buildPreviewItems(fresh, account, { suggest: true });
  const taken = new Set<number>();
  return items.map((it, i) => {
    const row = fresh[i];
    const twin = it.type === 'transfer' ? null : mergeCandidate(account, row.date, row.amount, taken);
    if (twin) taken.add(twin.id);
    return {
      ...it,
      // The typed one keeps its description and category: show those, so the review shows what stays.
      ...(twin
        ? {
            duplicate: null,
            include: true,
            description: twin.description || it.description,
            category_id: twin.category_id,
            hint: { label: 'Ya cargado', text: `Ya estaba cargado el ${twin.date}: se completa con la fecha, el comercio y las comisiones de Mercado Pago.` },
          }
        : {}),
      external_id: row.external_id,
      fees: row.fees,
      merge_with: twin?.id ?? null,
    };
  });
}

