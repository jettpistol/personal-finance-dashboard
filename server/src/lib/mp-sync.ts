export type ParsedReport = {
  /** Available balance at the start of the range (the report's first row), in cents. */
  initial: number | null;
  /** Balance at the end: the start plus every row after it. */
  closing: number | null;
  rows: (PreviewRow & { external_id: string; fees: Fee[] })[];
  /** Rows that move the balance but aren't movements (blocks, reserves). */
  skipped: number;
};

/** The released-money report as movements, detailed with the transactions report's rows. */
export function parseReleaseReport(text: string, detailText?: string | null): ParsedReport {
  const rows = table(text);
  const cols = new Set(Object.keys(rows[0] ?? {}));
  if (rows.length && !['DATE', 'RECORD_TYPE', 'NET_CREDIT_AMOUNT', 'NET_DEBIT_AMOUNT'].every((c) => cols.has(c)))
    throw new SyncError('El reporte de Mercado Pago no trae las columnas de fecha y montos. Tocá «Configurar reportes» y volvé a intentar.');
  const detail = new Map<string, Record<string, string>>();
  if (detailText) for (const d of table(detailText)) if (d.SOURCE_ID) detail.set(d.SOURCE_ID, d);

  let initial: number | null = null;
  let total = 0;
  let skipped = 0;
  const out: ParsedReport['rows'] = [];
  rows.forEach((r, i) => {
    const type = r.RECORD_TYPE.toLowerCase();
    const signed = mpAmount(r.NET_CREDIT_AMOUNT) - mpAmount(r.NET_DEBIT_AMOUNT);
    if (type === 'initial_available_balance') {
      initial = (initial ?? 0) + signed;
      return;
    }
    if (type.includes('total') || type.includes('final') || type.includes('subtotal')) return;
    total += signed;
    if (type !== 'release' || signed === 0) {
      if (signed !== 0) skipped++;
      return;
    }
    const what = (r.DESCRIPTION || '').toLowerCase();
    const d = r.SOURCE_ID ? detail.get(r.SOURCE_ID) : undefined;
    const merchant = [d?.STORE_NAME, d?.POS_NAME, d?.POI_WALLET_NAME, d?.POI_BANK_NAME, r.STORE_NAME, r.POS_NAME].find((x) => x && x.trim())?.trim() ?? null;
    const label = KINDS[what]?.[signed > 0 ? 0 : 1] ?? (what ? what[0].toUpperCase() + what.slice(1).replace(/_/g, ' ') : 'Movimiento');
    const extra = d?.DESCRIPTION && d.DESCRIPTION.toLowerCase() !== what ? d.DESCRIPTION : null;
    const description = [label, merchant, extra].filter(Boolean).join(' · ').slice(0, 300);
    const fees: Fee[] = [];
    for (const [col, kind] of FEE_COLUMNS) {
      const v = Math.abs(mpAmount(r[col]));
      if (v > 0) fees.push({ platform: MP_PLATFORM, kind, amount: v });
    }
    const withdrawal = WITHDRAWALS.has(what) && signed < 0;
    out.push({
      line: i + 2,
      date: localDate(r.DATE),
      description,
      amount: signed,
      currency: null,
      merchant,
      notes: r.SOURCE_ID ? `Mercado Pago · operación ${r.SOURCE_ID}` : null,
      ...(withdrawal ? { type: 'transfer' as const, hint: { label: 'Retiro', text: 'Elegí a qué cuenta fue el dinero.' } } : {}),
      external_id: `mp:${r.SOURCE_ID || '-'}:${stableId(r.DATE, r.SOURCE_ID, r.RECORD_TYPE, r.DESCRIPTION, r.NET_CREDIT_AMOUNT, r.NET_DEBIT_AMOUNT)}`,
      fees,
    });
  });
  return { initial, closing: initial === null ? null : initial + total, rows: out, skipped };
}

// ---- State ----

const getRow = (userId: number) => db().prepare('SELECT * FROM mp_sync WHERE user_id = ?').get(userId) as SyncRow | undefined;

function save(userId: number, patch: Partial<Omit<SyncRow, 'user_id'>>) {
  const cur = getRow(userId);
  const next = { status: 'fetching', live: 0, synced_until: null, last_sync_at: null, last_error: null, pending: null, review: null, opening: null, balance: null, balance_at: null, ...cur, ...patch };
  db()
    .prepare(
      `INSERT INTO mp_sync (user_id, status, live, synced_until, last_sync_at, last_error, pending, review, opening, balance, balance_at)
       VALUES (@user_id, @status, @live, @synced_until, @last_sync_at, @last_error, @pending, @review, @opening, @balance, @balance_at)
       ON CONFLICT(user_id) DO UPDATE SET status = @status, live = @live, synced_until = @synced_until, last_sync_at = @last_sync_at,
         last_error = @last_error, pending = @pending, review = @review, opening = @opening, balance = @balance, balance_at = @balance_at`,
    )
    .run({ ...next, user_id: userId });
}

const reviewOf = (r: SyncRow | undefined): Review => (r?.review ? (JSON.parse(r.review) as Review) : { items: [], dismissed: [], skipped: 0 });

function linkedAccount(userId: number): Account {
  const link = mpAccountState(userId).account;
  const account = link && loadAccounts().get(link.id);
  if (!account) throw new HttpError(400, 'Primero asigná tu cuenta de Mercado Pago en Cuentas.');
  return account;
}

/** What the settings screen and Cuentas show. */
export function syncView(userId: number) {
  const r = getRow(userId);
  const link = mpAccountState(userId).account;
  const appBalance = link ? (accountBalances(loadAccounts()).get(link.id) ?? null) : null;
  if (!r) return { status: 'off' as const, live: false, waiting: false, waiting_since: null, note: null, review_count: 0, last_sync_at: null, error: null, balance: null, balance_at: null, app_balance: appBalance };
  const review = reviewOf(r);
  return {
    status: r.status,
    live: !!r.live,
    // A report was asked for and isn't in yet: since when, and what Mercado Pago says.
    waiting: !!r.pending,
    waiting_since: r.pending ? new Date((JSON.parse(r.pending) as Pending).requested_at).toISOString() : null,
    note: r.pending ? ((JSON.parse(r.pending) as Pending).note ?? null) : null,
    review_count: review.items.length,
    last_sync_at: r.last_sync_at,
    synced_until: r.synced_until,
    error: r.last_error,
    balance: r.balance,
    balance_at: r.balance_at,
    app_balance: appBalance,
  };
}

/** The Cuentas tag of this person's Mercado Pago account: only they see it. */
export function liveTag(userId: number): { account_id: number; state: 'connected' | 'live' | 'error'; at: string | null } | null {
  const link = mpAccountState(userId).account;
  if (!link || !storedToken(userId)) return null;
  const r = getRow(userId);
  const state = r?.status === 'error' ? 'error' : r?.live ? 'live' : 'connected';
  return { account_id: link.id, state, at: r?.last_sync_at ?? null };
}

// ---- Talking to Mercado Pago ----

const iso = (ms: number) => new Date(Math.floor(ms / 1000) * 1000).toISOString().replace('.000Z', 'Z');

/** Midnight in the household's time zone of a YYYY-MM-DD date, in UTC ms. */
function localMidnight(date: string): number {
  const guess = Date.parse(`${date}T00:00:00Z`);
  const shown = Date.parse(`${new Date(guess).toLocaleString('sv-SE', { timeZone: config.timezone }).replace(' ', 'T')}Z`);
  return guess - (shown - guess);
}

async function requestRange(token: string, begin: string, end: string): Promise<Pending> {
  const cols = await ensureReportColumns(token, 'release_report');
  if (!cols.ok) throw new SyncError(`Mercado Pago no aceptó las columnas del reporte de dinero liberado${cols.message ? `: ${cols.message}` : ''}.`);
  const kinds: ReportKind[] = [];
  const r = await requestReport(token, 'release_report', begin, end);
  log(`pedir reporte de dinero liberado: código ${r.status}${mpMessage(r.body) ? ` (${mpMessage(r.body)})` : ''}`);
  if (r.status < 200 || r.status > 299 || r.status === 203)
    throw new SyncError(`Mercado Pago no generó el reporte de dinero liberado (código ${r.status})${mpMessage(r.body) ? `: ${mpMessage(r.body)}` : ''}.`);
  kinds.push('release_report');
  // The transactions report only adds store names; without it the import still works.
  try {
    if ((await ensureReportColumns(token, 'settlement_report')).ok) {
      const s = await requestReport(token, 'settlement_report', begin, end);
      if (s.status >= 200 && s.status < 300 && s.status !== 203) kinds.push('settlement_report');
    }
  } catch {
    /* optional */
  }
  return { begin, end, requested_at: Date.now(), kinds };
}

type ListEntry = {
  id?: number;
  begin_date?: string;
  end_date?: string;
  file_name?: string;
  status?: string;
  is_test?: boolean;
  generation_date?: string;
  date_created?: string;
  last_modified?: string;
};


/**
 * The report asked for in `p`, from Mercado Pago's list: same range (it may round the dates, so
 * the closest within a day and a half, made after the request), then downloaded. While it isn't
 * ready, says what Mercado Pago shows instead.
 */
async function fetchReport(token: string, kind: ReportKind, p: Pending): Promise<{ text: string } | { wait: string }> {
  const label = kind === 'release_report' ? 'dinero liberado' : 'todas las transacciones';
  const list = await mpGet(token, `/v1/account/${kind}/list`);
  if (list.status !== 200 || !Array.isArray(list.body)) throw new SyncError(`Mercado Pago no devolvió la lista de reportes de ${label} (código ${list.status}).`);
  const entries = (list.body as ListEntry[]).filter((e) => !e.is_test);
  const gap = (a: string | undefined, b: string) => (a && !Number.isNaN(Date.parse(a)) ? Math.abs(Date.parse(a) - Date.parse(b)) : Infinity);
  const made = (e: ListEntry) => Date.parse(e.generation_date ?? e.date_created ?? e.last_modified ?? '') || null;
  const mine = entries
    .map((e) => ({ e, off: gap(e.begin_date, p.begin) + gap(e.end_date, p.end) }))
    .filter(({ e, off }) => off < 36 * 3600_000 && (off < 4000 || (made(e) ?? Infinity) >= p.requested_at - 5 * 60_000))
    .sort((a, b) => a.off - b.off || (b.e.id ?? 0) - (a.e.id ?? 0));
  const newest = entries
    .slice(-3)
    .map((e) => `${e.begin_date ?? '?'}→${e.end_date ?? '?'} ${e.status ?? 'sin estado'}${e.file_name ? '' : ' sin archivo'}`)
    .join('; ');
  log(`${kind}: ${entries.length} en la lista${newest ? ` (últimos: ${newest})` : ''}; pedido ${p.begin}→${p.end}: ${mine.length ? 'encontrado' : 'no figura'}`);
  const entry = mine[0]?.e;
  if (!entry) return { wait: `El reporte de ${label} todavía no figura en la lista de Mercado Pago.` };
  // The docs say "processed" when it's ready; real accounts also answer "enabled". So the file
  // decides: with a file name it's downloaded, unless the status clearly says it's still being
  // made or it failed.
  const status = (entry.status ?? '').toLowerCase();
  const said = entry.status ? ` (estado «${entry.status.slice(0, 30)}»)` : '';
  if (FAILED.test(status)) throw new SyncError(`Mercado Pago no pudo generar el reporte de ${label}${said}. Probá de nuevo más tarde.`);
  if (!entry.file_name || IN_PROGRESS.test(status)) {
    if (!entry.file_name && status === 'processed') throw new SyncError('Mercado Pago terminó el reporte pero no indicó el nombre del archivo.');
    return { wait: `Mercado Pago está preparando el reporte de ${label}${said}.` };
  }
  if (!/^[\w.-]+\.csv$/i.test(entry.file_name)) throw new SyncError(`El reporte llegó como «${entry.file_name.slice(-40)}»; la app lee reportes en CSV.`);
  const file = await mpGet(token, `/v1/account/${kind}/${entry.file_name}`);
  log(`${kind}: descarga de ${entry.file_name}: código ${file.status}${typeof file.body === 'string' ? `, ${file.body.length} caracteres` : ''}`);
  if (file.status === 404) return { wait: `El archivo del reporte de ${label} todavía no está disponible.` };
  if (file.status !== 200 || typeof file.body !== 'string') throw new SyncError(`No se pudo descargar el reporte de ${label} (código ${file.status}).`);
  return { text: file.body };
}

